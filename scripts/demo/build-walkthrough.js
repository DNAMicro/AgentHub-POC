// Builds scripts/demo/live-walkthrough.js: the frame with every scene-N.js spliced in at /*@SCENES*/.
// playwright-cli run-code takes ONE function expression and cannot import, hence the build step.
// Exits 1 if a scene file is anything other than a single `scenes.push({...});` whose `n` matches its name.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), 'walkthrough');
const out = join(dirname(fileURLToPath(import.meta.url)), 'live-walkthrough.js');
const fail = (msg) => { console.error(`build-walkthrough: ${msg}`); process.exit(1); };

const frame = readFileSync(join(dir, 'frame.js'), 'utf8');
if (frame.split('/*@SCENES*/').length !== 2) fail('frame.js must contain exactly one /*@SCENES*/ line');

const files = readdirSync(dir).filter((f) => /^scene-\d+\.js$/.test(f)).sort((a, b) => parseInt(a.slice(6), 10) - parseInt(b.slice(6), 10));
if (!files.length) fail('no scene-N.js files found');

const parts = [];
const seen = new Set();
for (const f of files) {
  const src = readFileSync(join(dir, f), 'utf8');
  const want = parseInt(f.slice(6), 10);
  if (seen.has(want)) fail(`${f}: duplicate step number ${want}`);
  seen.add(want);
  const pushed = [];
  try {
    new Function('scenes', src)({ push: (s) => pushed.push(s), length: 0 });
  } catch (e) {
    fail(`${f}: does not compile or run its top level: ${e.message}`);
  }
  if (pushed.length !== 1) fail(`${f}: must push exactly one scene (pushed ${pushed.length})`);
  const s = pushed[0];
  if (s?.n !== want) fail(`${f}: scene n is ${s?.n}, expected ${want}`);
  if (typeof s.title !== 'string' || !s.title) fail(`${f}: missing title`);
  if (typeof s.run !== 'function') fail(`${f}: missing run()`);
  // Anything beyond the one scenes.push(...) statement is rejected: strip comments, then check the shape.
  const code = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').trim();
  if (!/^scenes\.push\(\{[\s\S]*\}\);$/.test(code)) fail(`${f}: must be exactly one \`scenes.push({...});\` statement`);
  parts.push(src.trim());
}

const header = '// GENERATED by scripts/demo/build-walkthrough.js — edit scripts/demo/walkthrough/ and rebuild; do not edit by hand.\n';
writeFileSync(out, header + frame.replace('/*@SCENES*/', parts.join('\n\n')));
console.log(`built ${out} from frame.js + ${files.join(', ')}`);
